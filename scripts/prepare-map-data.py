#!/usr/bin/env python3
from __future__ import annotations

import json
from pathlib import Path
from typing import Any
from urllib.request import urlopen


REPOSITORY_ROOT = Path(__file__).resolve().parents[1]
OUTPUT_DIR = (
    REPOSITORY_ROOT
    / "src"
    / "renderer"
    / "assets"
    / "map"
)

SOURCES = {
    "countries.geojson": {
        "url": "https://raw.githubusercontent.com/nvkelso/natural-earth-vector/master/geojson/ne_110m_admin_0_countries.geojson",
        "properties": [
            "ADMIN",
            "NAME",
            "NAME_PT",
            "ISO_A2",
            "ISO_A3",
            "LABELRANK",
            "POP_EST",
        ],
        "max_features": None,
    },
    "admin1.geojson": {
        "url": "https://raw.githubusercontent.com/nvkelso/natural-earth-vector/master/geojson/ne_50m_admin_1_states_provinces.geojson",
        "properties": [
            "name",
            "name_pt",
            "admin",
            "iso_a2",
            "adm1_code",
            "region",
            "scalerank",
        ],
        "max_features": None,
    },
    "populated-places.geojson": {
        "url": "https://raw.githubusercontent.com/nvkelso/natural-earth-vector/master/geojson/ne_50m_populated_places.geojson",
        "properties": [
            "NAME",
            "NAMEASCII",
            "ADM0NAME",
            "ADM1NAME",
            "LATITUDE",
            "LONGITUDE",
            "POP_MAX",
            "SCALERANK",
            "FEATURECLA",
        ],
        "max_features": 1400,
    },
}


def round_coordinates(value: Any) -> Any:
    if isinstance(value, list):
        if (
            len(value) >= 2
            and isinstance(value[0], (int, float))
            and isinstance(value[1], (int, float))
        ):
            return [round(value[0], 4), round(value[1], 4)]

        return [round_coordinates(item) for item in value]

    return value


def compact_feature(
    feature: dict[str, Any],
    allowed_properties: list[str],
) -> dict[str, Any]:
    properties = feature.get("properties") or {}
    next_properties = {
        key: properties[key]
        for key in allowed_properties
        if key in properties and properties[key] not in (None, "")
    }

    geometry = feature.get("geometry")
    if geometry and "coordinates" in geometry:
        geometry = {
            **geometry,
            "coordinates": round_coordinates(
                geometry["coordinates"],
            ),
        }

    return {
        "type": "Feature",
        "properties": next_properties,
        "geometry": geometry,
    }


def sort_populated_places(
    features: list[dict[str, Any]],
) -> list[dict[str, Any]]:
    return sorted(
        features,
        key=lambda feature: (
            feature.get("properties", {}).get("SCALERANK", 99),
            -int(
                feature.get("properties", {}).get("POP_MAX")
                or 0
            ),
        ),
    )


def download_json(url: str) -> dict[str, Any]:
    with urlopen(url, timeout=60) as response:
        return json.loads(
            response.read().decode("utf-8")
        )


def write_license() -> None:
    (OUTPUT_DIR / "MAP_DATA_LICENSE.md").write_text(
        """# ZeroHub map data

The generated GeoJSON files in this directory are derived from Natural Earth
public domain datasets, via the Natural Earth Vector repository:

https://github.com/nvkelso/natural-earth-vector

Natural Earth data is public domain. The generated files keep only compact
geometry and a small subset of descriptive properties needed by the local
ZeroHub map.

Generated by:

```bash
python3 scripts/prepare-map-data.py
```
""",
        encoding="utf-8",
    )


def main() -> None:
    OUTPUT_DIR.mkdir(
        parents=True,
        exist_ok=True,
    )

    for filename, config in SOURCES.items():
        source = download_json(
            str(config["url"]),
        )
        features = [
            compact_feature(
                feature,
                list(config["properties"]),
            )
            for feature in source.get("features", [])
        ]

        if filename == "populated-places.geojson":
            features = sort_populated_places(
                features,
            )

        max_features = config["max_features"]
        if isinstance(max_features, int):
            features = features[:max_features]

        output = {
            "type": "FeatureCollection",
            "features": features,
        }

        (OUTPUT_DIR / filename).write_text(
            json.dumps(
                output,
                ensure_ascii=False,
                separators=(",", ":"),
            ),
            encoding="utf-8",
        )

    write_license()


if __name__ == "__main__":
    main()
